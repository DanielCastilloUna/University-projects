    @Override
    public void propertyChange(PropertyChangeEvent evt) {
        switch (evt.getPropertyName()) {
            case Model.CATEGORIAS:
                CategoriaRecurso[] cats = model.getCategorias().toArray(new CategoriaRecurso[0]);
                categoriaFld.setModel(new DefaultComboBoxModel<>(cats));

                //Combo de filtro con opcion vacia/ todas al inicio

                DefaultComboBoxModel<CategoriaRecurso> filtroModel = new DefaultComboBoxModel<>();
                filtroModel.addElement(null);
                for(CategoriaRecurso c: cats){
                    filtroModel.addElement(c);
                }
                filtroCategoriaFld.setModel(filtroModel);
                break;



            case Model.LIST:
                int[] cols = {TableModel.ID, TableModel.CATEGORIA, TableModel.DESCRIPCION};
                recursosTable.setModel(new TableModel(cols, model.getList()));
                break;
            case Model.CURRENT:
                Recurso curr = model.getCurrent();
                idFld.setText(curr.getId()!=null ? curr.getId():"");
                descripcionFld.setText(curr.getDescripcion()!= null ? curr.getDescripcion():"");
                categoriaFld.setSelectedItem(model.getCurrent().getCategoria());

                idFld.setBackground(null);
                idFld.setToolTipText(curr.getId() != null && !curr.getId().isBlank() ? null : "Se asigna automáticamente al guardar");
                break;
        }
        this.panelPrincipal.revalidate();
    }

    public Recurso take() {
        Recurso e = new Recurso();
        e.setId(idFld.getText());
        e.setDescripcion(descripcionFld.getText());
        e.setCategoria((CategoriaRecurso) categoriaFld.getSelectedItem());
        return e;
    }

    private boolean validate_() {
        boolean valid = true;

        if (descripcionFld.getText().isEmpty()) {
            valid = false;
            descripcionFld.setBackground(Color.PINK);
            descripcionFld.setToolTipText("Descripcion requerida");
        } else {
            descripcionFld.setBackground(null);
            descripcionFld.setToolTipText(null);
        }

        if (categoriaFld.getSelectedItem() == null) {
            valid = false;
            categoriaFld.setBackground(Color.PINK);
            categoriaFld.setToolTipText("Categoria requerida");
        } else {
            categoriaFld.setBackground(null);
            categoriaFld.setToolTipText(null);
        }
        return valid;
    }
